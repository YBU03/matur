// Ekspor laporan bulanan ke sheet "Laporan Keuangan" format Ruma (tata letak sama dengan file manual,
// sehingga bisa diimpor kembali lewat parseLaporan).
import type { Worksheet } from "exceljs";
import { hitung, namaBulan, type Laporan, type Perusahaan } from "./laporan";

const RP = '_("Rp"* #,##0_);_("Rp"* (#,##0);_("Rp"* "-"_);_(@_)';
const angkaTerbilang = ["", "Satu", "Dua", "Tiga", "Empat", "Lima", "Enam", "Tujuh", "Delapan", "Sembilan", "Sepuluh", "Sebelas", "Dua Belas"];

export function isiSheetLaporan(ws: Worksheet, l: Laporan, pt: Perusahaan) {
  const h = hitung(l);
  const bulan = namaBulan(l.periode);
  const tglAkhir = new Date(Date.UTC(Number(l.periode.slice(0, 4)), Number(l.periode.slice(5, 7)), 0));
  let r = 1;
  const set = (row: number, col: string, v: unknown, o: { bold?: boolean; rp?: boolean; size?: number } = {}) => {
    const c = ws.getCell(`${col}${row}`);
    c.value = v as never;
    if (o.bold || o.size) c.font = { bold: o.bold, size: o.size };
    if (o.rp) c.numFmt = RP;
  };
  set(3, "C", pt.nama.toUpperCase(), { bold: true, size: 14 });
  if (pt.alamat) set(4, "C", pt.alamat);
  if (pt.email || pt.telepon) set(5, "C", `Email: ${pt.email ?? "-"} Telp: ${pt.telepon ?? "-"}`);
  set(9, "A", `LAPORAN KEUANGAN ${l.nama_outlet.toUpperCase()}`, { bold: true, size: 14 });
  r = 12;
  const isian = (k: string, v: unknown) => {
    set(r, "A", k);
    set(r, "D", ":");
    set(r, "E", v);
    r++;
  };
  isian("Nama Outlet", l.nama_outlet);
  if (l.outlet?.tgl_mulai) {
    isian("Tanggal Mulai Operasional", new Date(l.outlet.tgl_mulai + "T00:00:00Z"));
    ws.getCell(`E${r - 1}`).numFmt = "dd mmmm yyyy";
  }
  isian("Jam Operasional", l.outlet?.jam_operasional ?? "-");
  isian("Periode Laporan", `Per ${bulan}`);
  isian("Mitra", l.mitra ?? "-");
  isian("Penanggung Jawab Laporan", l.pj_laporan ?? "-");
  isian("Jumlah Karyawan", `${l.karyawan.length} (${angkaTerbilang[l.karyawan.length] ?? l.karyawan.length})`);
  l.karyawan.forEach((k, i) => set(r++, "E", `${i + 1}. ${k}`));
  r += 3;
  const judul = (t: string) => (set(r, "A", `· ${t}`, { bold: true }), (r += 2));
  judul("MODAL OUTLET");
  ["Tanggal", "", "Keterangan", "", "Debit", "Kredit", "", "Saldo"].forEach((t, i) => t && set(r, "ABCDEFGH"[i], t, { bold: true }));
  r++;
  set(r, "A", new Date(l.periode + "T00:00:00Z"));
  ws.getCell(`A${r}`).numFmt = "dd/mm/yyyy";
  set(r, "C", "Saldo Awal");
  set(r, "E", l.modal_awal, { rp: true });
  set(r, "H", l.modal_awal, { rp: true });
  r += 3;
  judul("HARGA POKOK PENJUALAN");
  r++;
  const g = (k: string, v: number, op?: string, bold = false) => {
    set(r, "A", k, { bold });
    set(r, "G", v, { rp: true, bold });
    if (op) set(r, "I", op);
    r++;
  };
  g("Persedian awal barang dagangan", l.persediaan_awal);
  g("Pembelian bahan baku", l.pembelian, Number(l.tagihan_titipan ?? 0) ? undefined : "(+)");
  if (Number(l.tagihan_titipan ?? 0)) g(`Tagihan titipan${(l.rincian_titipan ?? []).length === 1 ? ` ${l.rincian_titipan![0].produsen}` : " produsen"}`, Number(l.tagihan_titipan), "(+)");
  r++;
  g("Barang yang tersedia untuk di jual", h.tersedia, undefined, true);
  g("Persedian akhir barang dagangan", l.persediaan_akhir, "(-)");
  r++;
  g("Harga pokok penjualan", h.hpp, undefined, true);
  r += 3;
  judul("LABA RUGI");
  r++;
  set(r++, "A", "Pendapatan", { bold: true });
  for (const p of l.pendapatan) (set(r, "B", p.nama), set(r, "F", Number(p.jumlah), { rp: true }), r++);
  set(r, "B", "Discount");
  set(r, "F", -l.diskon, { rp: true });
  set(r++, "G", "(+)");
  set(r, "A", "Total penjualan", { bold: true });
  set(r++, "H", h.totalPenjualan, { rp: true, bold: true });
  r++;
  set(r++, "A", "Pengeluaran", { bold: true });
  set(r, "B", "Bahan baku");
  set(r++, "F", h.hpp, { rp: true });
  set(r, "A", "Total pengeluaran", { bold: true });
  set(r, "H", h.hpp, { rp: true, bold: true });
  set(r++, "I", "(+)");
  set(r, "A", "Laba Kotor", { bold: true });
  set(r++, "H", h.labaKotor, { rp: true, bold: true });
  r++;
  set(r++, "A", "Beban Operasional : ", { bold: true });
  set(r, "B", `Sedekah ${String(l.persen_sedekah).replace(".", ",")}%`);
  set(r++, "F", l.sedekah, { rp: true });
  for (const b of l.beban) (set(r, "B", b.nama), set(r, "F", Number(b.jumlah), { rp: true }), r++);
  set(r, "A", "Total beban operasional", { bold: true });
  set(r, "H", h.totalBeban, { rp: true, bold: true });
  set(r++, "I", "(-)");
  set(r, "A", "Laba Bersih", { bold: true });
  set(r++, "H", h.labaBersih, { rp: true, bold: true });
  r += 3;
  judul("SHARING PROFIT");
  r++;
  g("Modal Awal", l.modal_awal);
  g("Laba Outlet", h.labaBersih, "(+)");
  g("Modal", h.modal, undefined, true);
  for (const b of l.bagi_hasil) g(/pengelola/i.test(b.nama) ? `Untuk ${b.nama} ${String(b.persen).replace(".", ",")}%` : `Pembagian Hasil a.n ${b.nama} ${String(b.persen).replace(".", ",")}%`, Number(b.jumlah));
  g("Modal Akhir", l.modal_awal, undefined, true);
  r += 3;
  judul("SALDO SEDEKAH");
  ["Tanggal", "", "Keterangan", "", "Debit", "Kredit", "", "Saldo"].forEach((t, i) => t && set(r, "ABCDEFGH"[i], t, { bold: true }));
  r++;
  set(r, "A", tglAkhir);
  ws.getCell(`A${r}`).numFmt = "dd/mm/yyyy";
  set(r, "C", "Saldo");
  set(r, "E", l.sedekah, { rp: true });
  set(r++, "H", l.sedekah, { rp: true });
  set(r, "C", "Kelola Pusat");
  set(r, "F", l.sedekah, { rp: true });
  set(r++, "H", 0, { rp: true });
  r += 3;
  set(r++, "A", "Tabel Penerimaan Transfer Periode Pelaporan", { bold: true });
  const bank = l.transfer.find((t) => t.bank)?.bank ?? "Bank";
  ["No", "Keterangan", "", "", "Jumlah", bank].forEach((t, i) => t && set(r, "ABCDEF"[i], t, { bold: true }));
  r++;
  set(r, "F", "No Rekening", { bold: true });
  set(r++, "H", "Atas Nama", { bold: true });
  l.transfer.forEach((t, i) => {
    set(r, "A", i + 1);
    set(r, "B", t.keterangan);
    set(r, "E", Number(t.jumlah), { rp: true });
    if (t.no_rekening) set(r, "F", t.no_rekening);
    if (t.atas_nama) set(r, "H", t.bank && t.bank !== bank ? `${t.atas_nama} (${t.bank})` : t.atas_nama);
    r++;
  });
  set(r, "A", "Total", { bold: true });
  set(r++, "E", h.totalTransfer, { rp: true, bold: true });
  r++;
  const terbit = l.tgl_terbit ? new Date(l.tgl_terbit + "T00:00:00").toLocaleDateString("id-ID", { day: "numeric", month: "long", year: "numeric" }) : "";
  set(r, "F", `${l.kota_terbit ?? "Purbalingga"}, ${terbit}`);
  r += 6;
  set(r++, "G", l.penandatangan ?? "", { bold: true });
  set(r, "G", l.jabatan_penandatangan ?? "");
  ws.getColumn("A").width = 14;
  ws.getColumn("B").width = 30;
  for (const c of ["E", "F", "G", "H"]) ws.getColumn(c).width = 18;
}
