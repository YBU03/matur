-- Integration test, no production sale or attendance changes. Always rolled back.
begin;
do $$
declare
 admin uuid; staf uuid:=gen_random_uuid(); o uuid:=gen_random_uuid(); other_o uuid:=gen_random_uuid();
 un text:='test-'||replace(o::text,'-',''); r jsonb; version timestamptz; tablet uuid; denied boolean; message text;
 sale_count bigint; cash_count bigint; old_time timestamptz:=clock_timestamp()-interval '1 minute';
begin
 select u.id into admin from public.pengguna u join public.penugasan t on t.pengguna_id=u.id where u.status='aktif' and t.peran in ('owner','admin_pusat') limit 1;
 if admin is null then raise exception 'Requires an active central admin';end if;
 select count(*) into sale_count from public.transaksi;
 select count(*) into cash_count from public.sesi_kas;
 insert into public.outlet(id,nama) values(o,'Testing fixture rollback'),(other_o,'Non-demo fixture rollback');
 insert into auth.users(id,email) values(staf,staf::text||'@test.invalid');
 insert into public.pengguna(id,nama,email,status) values(staf,'HRD test',staf::text||'@test.invalid','aktif');
 insert into public.penugasan(pengguna_id,peran,outlet_id) values(staf,'hrd',o);
 insert into matur_internal.pos_testing(outlet_id,aktif) values(o,true);
 select diubah_at into version from matur_internal.pos_testing where outlet_id=o;
 perform set_config('request.jwt.claim.sub',admin::text,true);
 if not public.status_testing_pos(o) then raise exception 'Central admin cannot read testing mode';end if;
 denied:=false;
 begin perform public.atur_testing_pos(other_o,true,version);exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Non-demo outlet can be enabled';end if;
 perform set_config('request.jwt.claim.sub',staf::text,true);
 denied:=false;
 begin perform public.atur_testing_pos(o,false,version);exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'HRD can change testing mode';end if;
 denied:=false;
 begin perform public.panel_testing_pos();exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'HRD can read central testing panel';end if;
 perform set_config('request.jwt.claim.sub','',true);
 denied:=false;
 begin perform public.status_testing_pos(o);exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Anonymous can access testing mode';end if;
 perform set_config('request.jwt.claim.sub',admin::text,true);
 perform public.atur_akses_pos_outlet(o,un,'Test-POS-password-123',true);
 r:=public.masuk_pos_outlet(un,'Test-POS-password-123',repeat('q',64),repeat('w',48));
 if r->>'email' is null then raise exception 'Outlet login failed';end if;
 select id into tablet from public.pengguna where email=r->>'email';
 perform set_config('request.jwt.claim.sub',tablet::text,true);
 if not public.status_testing_pos(o) then raise exception 'Tablet cannot access demo mode';end if;
 r:=public.katalog_testing_pos(o,repeat('q',64));
 if jsonb_typeof(r)<>'array' then raise exception 'Catalog is not an array';end if;
 -- No clock-in or cash session exists, yet the training catalog can be opened.
 denied:=false;
 begin perform public.katalog_testing_pos(o,'wrong-device');exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Wrong device token accepted';end if;
 denied:=false;
 begin perform public.status_testing_pos(other_o);exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Tablet can read another outlet';end if;
 message:='';
 begin perform public.buat_transaksi(jsonb_build_object('outlet_id',o,'client_id',gen_random_uuid(),'device_token',repeat('q',64)));exception when raise_exception then message:=sqlerrm;end;
 if message not like 'Mode testing aktif%' then raise exception 'Live checkout not blocked: %',message;end if;
 message:='';
 begin perform public.buat_transaksi(jsonb_build_object('outlet_id',o,'client_id',gen_random_uuid(),'device_token',repeat('q',64),'sinkron_offline',true,'waktu_asli',clock_timestamp()));exception when raise_exception then message:=sqlerrm;end;
 if message not like 'Mode testing aktif%' then raise exception 'New offline checkout not blocked';end if;
 message:='';
 begin perform public.buat_transaksi(jsonb_build_object('outlet_id',o,'client_id',gen_random_uuid(),'device_token',repeat('q',64),'sinkron_offline',true,'waktu_asli',old_time));exception when raise_exception then message:=sqlerrm;end;
 if message like 'Mode testing aktif%' or message='' then raise exception 'Historical queue handling incorrect';end if;
 -- Turning off restores ordinary POS checks; it never grants a shift or cash session.
 perform set_config('request.jwt.claim.sub',admin::text,true);
 perform public.atur_testing_pos(o,false,version);
 if public.status_testing_pos(o) then raise exception 'Disable did not take effect';end if;
 denied:=false;
 begin perform public.atur_testing_pos(o,true,version);exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Stale admin update accepted';end if;
 perform set_config('request.jwt.claim.sub',tablet::text,true);
 denied:=false;
 begin perform public.katalog_testing_pos(o,repeat('q',64));exception when raise_exception then denied:=true;end;
 if not denied then raise exception 'Disabled demo catalog accessible';end if;
 message:='';
 begin perform public.buat_transaksi(jsonb_build_object('outlet_id',o,'client_id',gen_random_uuid(),'device_token',repeat('q',64)));exception when raise_exception then message:=sqlerrm;end;
 if message='' or message like 'Mode testing aktif%' then raise exception 'Ordinary POS checks not restored';end if;
 if (select count(*) from public.transaksi)<>sale_count or (select count(*) from public.sesi_kas)<>cash_count then raise exception 'Training created real financial records';end if;
 if has_table_privilege('authenticated','matur_internal.pos_testing','select') or has_function_privilege('anon','public.atur_testing_pos(uuid,boolean,timestamptz)','execute') then raise exception 'Grants too broad';end if;
 if not exists(select 1 from public.log_aktivitas where entitas_id=o::text and aksi='atur_testing_pos' and pengguna_id=admin) then raise exception 'Toggle audit missing';end if;
end $$;
select 'PASS: demo allowlist, central roles, outlet/device scope, no shift required, toggle/version/audit, blocked live sales, historical sync, no real cash/sales' as result;
rollback;
